//! Compiles the vendored emulator protos with `protox` (pure Rust, no `protoc`) and writes the
//! tonic client and server code to `src/proto/generated.rs` of the crate passed as argument.

use std::{env, fs, path::PathBuf};

const PROTO_FILE: &str = "emulator_controller.proto";
const PACKAGE: &str = "android.emulation.control";

fn main() {
    let crate_dir = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .expect("usage: warpium_emulator_codegen <path to crates/warpium_emulator>");
    let proto_dir = crate_dir.join("proto");
    let out_dir = env::temp_dir().join(format!("warpium_emulator_codegen_{}", std::process::id()));
    fs::create_dir_all(&out_dir).expect("create temporary output dir");

    let fds = protox::compile([PROTO_FILE], [&proto_dir]).expect("compile protos with protox");

    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .build_transport(false)
        .generate_default_stubs(true)
        // Only the fake emulator in tests serves this API.
        .server_mod_attribute(PACKAGE, r#"#[cfg(any(test, feature = "test-support"))]"#)
        // Frame pixels become `bytes::Bytes`, sliced from the HTTP/2 buffer without a copy.
        .bytes(".")
        .out_dir(&out_dir)
        .compile_fds(fds)
        .expect("generate tonic code");

    let generated =
        fs::read_to_string(out_dir.join(format!("{PACKAGE}.rs"))).expect("read generated code");
    let _ = fs::remove_dir_all(&out_dir);
    let header = format!(
        "// @generated by script/warpium/gen-emulator-proto from proto/{PROTO_FILE}. Do not edit.\n"
    );
    fs::write(
        crate_dir.join("src/proto/generated.rs"),
        header + &generated,
    )
    .expect("write src/proto/generated.rs");
}
